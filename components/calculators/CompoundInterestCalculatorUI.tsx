'use client';

import React from 'react';
import { useForm } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import { z } from 'zod';
import { calculateCompoundInterest } from '@/lib/calculators';
import { formatCurrency } from '@/lib/utils';
import { ResultDisplay } from '@/components/ui/result-display';
import { Input } from '@/components/ui/input';
import { CalculationResults } from '@/components/ui/calculation-results';
import { InputError } from '@/components/ui/input-error';

const schema = z.object({
  initialDeposit: z.number().min(0, 'Minimum initial deposit $0'),
  monthlyContribution: z.number().min(0, 'Contribution cannot be negative'),
  annualInterestRate: z.number().min(0, 'Rate cannot be negative').max(50, 'Max 50%'),
  years: z.number().min(1, 'Min 1 year').max(50, 'Max 50 years'),
});

type FormValues = z.infer<typeof schema>;

export function CompoundInterestCalculatorUI() {
  const { register, watch, formState: { errors, isValid } } = useForm<FormValues>({
    resolver: zodResolver(schema),
    defaultValues: {
      initialDeposit: 10000,
      monthlyContribution: 500,
      annualInterestRate: 8,
      years: 20,
    },
    mode: 'onChange',
  });

  const values = watch();
  const results = calculateCompoundInterest({
    initialDeposit: Number(values.initialDeposit) || 0,
    monthlyContribution: Number(values.monthlyContribution) || 0,
    annualInterestRate: Number(values.annualInterestRate) || 0,
    years: Number(values.years) || 0,
  });

  return (
    <div className="grid grid-cols-1 lg:grid-cols-12 gap-8">
      <div className="lg:col-span-7 space-y-5">
        <div className="grid grid-cols-2 gap-4">
          <div>
            <label className="block text-xs font-semibold text-zinc-300 uppercase tracking-wider mb-1.5">
              Initial Deposit ($)
            </label>
            <Input type="number" step="500" {...register('initialDeposit', { valueAsNumber: true })} />
            <InputError message={errors.initialDeposit?.message} />
          </div>

          <div>
            <label className="block text-xs font-semibold text-zinc-300 uppercase tracking-wider mb-1.5">
              Monthly Contribution ($)
            </label>
            <Input type="number" step="50" {...register('monthlyContribution', { valueAsNumber: true })} />
            <InputError message={errors.monthlyContribution?.message} />
          </div>
        </div>

        <div className="grid grid-cols-2 gap-4">
          <div>
            <label className="block text-xs font-semibold text-zinc-300 uppercase tracking-wider mb-1.5">
              Estimated Return Rate (%)
            </label>
            <Input type="number" step="0.1" {...register('annualInterestRate', { valueAsNumber: true })} />
            <InputError message={errors.annualInterestRate?.message} />
          </div>

          <div>
            <label className="block text-xs font-semibold text-zinc-300 uppercase tracking-wider mb-1.5">
              Investment Horizon (Years)
            </label>
            <Input type="number" step="1" {...register('years', { valueAsNumber: true })} />
            <InputError message={errors.years?.message} />
          </div>
        </div>
      </div>

      <div className="lg:col-span-5 space-y-4">
        <CalculationResults isValid={isValid}>
          <>
            <ResultDisplay
              label="Future Investment Balance"
              value={formatCurrency(results.futureValue)}
              subText={`Estimated total balance after ${values.years} years`}
              isPrimary
            />
            <ResultDisplay
              label="Total Contributions Made"
              value={formatCurrency(results.totalContributions)}
              subText="Principal plus monthly contributions"
            />
            <ResultDisplay
              label="Total Compound Interest Earned"
              value={formatCurrency(results.totalInterestEarned)}
              subText="Growth generated by compound interest"
            />
          </>
        </CalculationResults>
      </div>
    </div>
  );
}
